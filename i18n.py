def set_language(lang: str):
    global _LANG
    _LANG = lang if lang in _STRINGS else "en"


def get_language() -> str:
    return _LANG

def t(key: str) -> str:
    """Get translated string for key. Falls back to English, then key itself."""
    return _STRINGS.get(_LANG, _STRINGS["en"]).get(key, _STRINGS["en"].get(key, key))


def tr_text(text: str) -> str:
    """Translate exact English UI phrases while leaving user-entered text alone."""
    if _LANG == "pl":
        return _TEXT_TRANSLATIONS_PL.get(str(text), str(text))
    return str(text)


def month_abbr(month: int) -> str:
    return _MONTHS.get(_LANG, _MONTHS["en"])["abbr"][month - 1]


def month_full(month: int) -> str:
    return _MONTHS.get(_LANG, _MONTHS["en"])["full"][month - 1]


def weekday_abbr(weekday: int) -> str:
    return _MONTHS.get(_LANG, _MONTHS["en"])["weekday_abbr"][weekday]


def item_count(count: int) -> str:
    if _LANG == "pl":
        if count == 1:
            return "1 pozycja"
        if 2 <= count % 10 <= 4 and count % 100 not in (12, 13, 14):
            return f"{count} pozycje"
        return f"{count} pozycji"
    return f"{count} item{'s' if count != 1 else ''}"


